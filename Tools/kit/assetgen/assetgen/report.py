"""report and budget: Docs/STATS/generation.json and Docs/COSTS.md, rendered from the ledger (never hand-kept)."""

from .ledger import totals
from .util import utc_iso, write_json_atomic, write_text_atomic


def budget_view(ctx):
    t = totals(ctx.ledger.lines(), ctx.budget)
    out = {}
    for p, s in t.items():
        out[p] = {k: s.get(k) for k in ("unit", "spent", "reserved", "soft", "hard", "remaining")}
    return {"ok": True, "providers": out}


def _md_cell(v):
    return str("" if v is None else v).replace("|", "\\|").replace("\n", " ")


def build(ctx):
    lines = ctx.ledger.lines()
    budget = ctx.budget if ctx.layout.budget.is_file() else None
    t = totals(lines, budget)
    providers = {p: {"unit": s.get("unit"), "spent": s["spent"], "reserved": s["reserved"], "soft": s.get("soft"), "hard": s.get("hard"),
                     "calls": s["calls"], "orphans": s["orphans"]} for p, s in sorted(t.items())}
    attempted = {l["attempt_id"] for l in lines if l.get("event") == "reserve" and l.get("attempt_id")}
    accepted = {l["attempt_id"] for l in lines if l.get("event") == "accept"}
    rejected = {l["attempt_id"] for l in lines if l.get("event") == "reject"}
    stats = {"schema": 1, "utc": utc_iso(), "providers": providers,
             "assets": {"attempted": len(attempted), "accepted": len(accepted), "rejected": len(rejected - accepted)}}
    by_attempt = {}
    for l in lines:
        aid = l.get("attempt_id")
        if not aid:
            continue
        row = by_attempt.setdefault(aid, {"attempt": aid, "utc": l.get("utc"), "provider": l.get("provider"), "endpoint": "", "request_id": "", "est": "", "actual": "", "unit": "", "result": ""})
        ev = l.get("event")
        if ev == "reserve":
            row.update(endpoint=l.get("endpoint", ""), est=l.get("est", ""), unit=l.get("unit", ""), utc=l.get("utc"))
        elif ev == "receipt":
            row["request_id"] = l.get("request_id", "")
        elif ev == "settle":
            row["actual"] = l.get("actual", "")
            row["result"] = row["result"] or "settled"
        elif ev == "release":
            row["result"] = "released: " + str(l.get("reason", ""))[:60]
        elif ev in ("accept", "reject"):
            row["result"] = f"{ev}ed: " + str(l.get("reason", ""))[:60]
    md = ["# Generation costs", "", f"Generated by `assetgen report` at {stats['utc']} from `ArtSource/_gen/ledger.jsonl`. Do not edit by hand.", "",
          "| Provider | Unit | Spent | Reserved | Soft | Hard | Calls | Orphans |", "|---|---|---|---|---|---|---|---|"]
    for p, s in providers.items():
        md.append("| " + " | ".join(_md_cell(x) for x in (p, s["unit"], s["spent"], s["reserved"], s["soft"], s["hard"], s["calls"], s["orphans"])) + " |")
    md += ["", f"Assets: {stats['assets']['attempted']} attempted, {stats['assets']['accepted']} accepted, {stats['assets']['rejected']} rejected.", "",
           "| UTC | Attempt | Provider | Endpoint | Request id | Est | Actual | Unit | Result |", "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(by_attempt.values(), key=lambda r: (r["utc"] or "", r["attempt"])):
        md.append("| " + " | ".join(_md_cell(r[k]) for k in ("utc", "attempt", "provider", "endpoint", "request_id", "est", "actual", "unit", "result")) + " |")
    orphans = [l for l in lines if l.get("event") == "orphan"]
    if orphans:
        md += ["", "## Orphans (paid work with no attempt)", "", "| UTC | Provider | Request id | Reason |", "|---|---|---|---|"]
        for o in orphans:
            md.append("| " + " | ".join(_md_cell(x) for x in (o.get("utc"), o.get("provider"), o.get("request_id") or "", o.get("reason", ""))) + " |")
    return stats, "\n".join(md) + "\n"


def report(ctx):
    stats, md = build(ctx)
    write_json_atomic(ctx.layout.generation_stats, stats)
    write_text_atomic(ctx.layout.costs, md)
    return {"ok": True, "stats": ctx.layout.rel(ctx.layout.generation_stats), "costs": ctx.layout.rel(ctx.layout.costs), "providers": stats["providers"], "assets": stats["assets"]}
